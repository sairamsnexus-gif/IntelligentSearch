import { chromium } from "playwright";
const B = "http://localhost:3100";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const ctx = await browser.newContext({ viewport: { width: 1600, height: 1000 }, deviceScaleFactor: 1, acceptDownloads: true });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
page.on("console", (m) => { if (m.type() === "error") console.log("CONSOLE", m.text()); });
await page.goto(`${B}/login`);
await page.fill('input[type=email]', "op@example.com");
await page.fill('input[type=password]', "correct-horse-battery");
await page.click('button[type=submit]');
await page.waitForURL(B + "/");
await page.getByText("use example request").click();
console.log("synthetic checked:", await page.getByTestId("nexus-synthetic").isChecked());
await page.getByTestId("nexus-start").click();
await page.waitForFunction(() => document.querySelector('[data-testid=nexus-status]')?.textContent === "completed", null, { timeout: 120000 });
await page.screenshot({ path: "/tmp/claude-0/shots/1-complete.png", fullPage: true });
for (const t of ["B · Possible matches", "D · Source evidence", "Coverage", "F · Unresolved leads", "E · Investigation trail"]) {
  await page.getByRole("tab", { name: new RegExp(t.replace(/[·]/g, ".")) }).click();
  await page.waitForTimeout(300);
}
await page.getByRole("tab", { name: /Possible matches/ }).click();
await page.getByTestId("nexus-confirm").first().click();
const [dl] = await Promise.all([page.waitForEvent("download"), page.getByTestId("nexus-export").click()]);
console.log("download:", dl.suggestedFilename());
console.log("graph nodes:", await page.getByTestId("nexus-graph-node").count());
console.log("still visible after export:", await page.getByTestId("nexus-graph").isVisible(), await page.getByTestId("nexus-unsaved").count());
await page.screenshot({ path: "/tmp/claude-0/shots/2-matches.png", fullPage: true });
// reload -> recovery banner
await page.reload();
await page.getByTestId("nexus-recovery").waitFor({ timeout: 10000 });
await page.getByTestId("nexus-restore").click();
console.log("restored status:", await page.getByTestId("nexus-status").textContent());
const m = await browser.newContext({ viewport: { width: 390, height: 844 }, storageState: await ctx.storageState() });
const mp = await m.newPage();
await mp.goto(B + "/");
await mp.screenshot({ path: "/tmp/claude-0/shots/3-mobile.png", fullPage: false });
const sw = await mp.evaluate(() => document.documentElement.scrollWidth);
console.log("mobile scrollWidth", sw);
await browser.close();
